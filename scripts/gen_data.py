#!/usr/bin/env python3
"""Generate src/bidi-data.ts from the Unicode Character Database files in data/ucd-17.0.0/.

The same tables (ranges, mirroring pairs, bracket pairs) are emitted for every port,
so all ports classify every code point identically.

Usage: python3 scripts/gen_data.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
UCD = ROOT / "data" / "ucd-17.0.0"
UNICODE_VERSION = "17.0.0"

# Order is part of the SPEC (section 2.1): class index used in the tables.
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
LONG = {
    "Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Number": "EN",
    "European_Separator": "ES", "European_Terminator": "ET", "Arabic_Number": "AN",
    "Common_Separator": "CS", "Nonspacing_Mark": "NSM", "Boundary_Neutral": "BN",
    "Paragraph_Separator": "B", "Segment_Separator": "S", "White_Space": "WS", "Other_Neutral": "ON",
    "Left_To_Right_Embedding": "LRE", "Left_To_Right_Override": "LRO", "Right_To_Left_Embedding": "RLE",
    "Right_To_Left_Override": "RLO", "Pop_Directional_Format": "PDF", "Left_To_Right_Isolate": "LRI",
    "Right_To_Left_Isolate": "RLI", "First_Strong_Isolate": "FSI", "Pop_Directional_Isolate": "PDI",
}


def parse_range(s):
    s = s.strip()
    if ".." in s:
        a, b = s.split("..")
        return int(a, 16), int(b, 16)
    return int(s, 16), int(s, 16)


def bidi_classes():
    table = bytearray(0x110000)  # index into CLASSES
    text = (UCD / "DerivedBidiClass.txt").read_text(encoding="utf-8")
    # @missing lines first, in file order (later lines override earlier ones)
    for m in re.finditer(r"^# @missing: ([0-9A-F.]+); (\w+)", text, re.M):
        a, b = parse_range(m.group(1))
        table[a:b + 1] = bytes([CLASSES.index(LONG[m.group(2)])]) * (b - a + 1)
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        rng, cls = [x.strip() for x in line.split(";")]
        a, b = parse_range(rng)
        table[a:b + 1] = bytes([CLASSES.index(cls)]) * (b - a + 1)
    ranges = []  # (start, class) where class holds until next start
    prev = None
    for cp in range(0x110000):
        if table[cp] != prev:
            ranges.append((cp, table[cp]))
            prev = table[cp]
    return ranges


def mirroring():
    pairs = []
    for line in (UCD / "BidiMirroring.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            a, b = [int(x.strip(), 16) for x in line.split(";")]
            pairs.append((a, b))
    return sorted(pairs)


def brackets():
    out = []
    for line in (UCD / "BidiBrackets.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            a, b, t = [x.strip() for x in line.split(";")]
            out.append((int(a, 16), int(b, 16), 1 if t == "o" else 2))
    return sorted(out)


def main():
    ranges = bidi_classes()
    mirr = mirroring()
    brk = brackets()
    starts = ",".join(str(s) for s, _ in ranges)
    classes = "".join(chr(ord("A") + c) for _, c in ranges)
    lines = [
        "// Generated by scripts/gen_data.py from the Unicode Character Database "
        f"{UNICODE_VERSION} (data/ucd-17.0.0). Do not edit.",
        "",
        f"export const UNICODE_VERSION = '{UNICODE_VERSION}'",
        "",
        "/** Bidi_Class names in table order (SPEC 2.1). */",
        "export const CLASS_NAMES = [" + ", ".join(f"'{c}'" for c in CLASSES) + "] as const",
        "",
        "/** First code point of each range; the range lasts until the next start. */",
        f"export const RANGE_STARTS: readonly number[] = [{starts}]",
        "",
        "/** Class of each range as a letter: 'A' + index into CLASS_NAMES. */",
        f"export const RANGE_CLASSES = '{classes}'",
        "",
        "/** Bidi_Mirroring_Glyph: flat [code point, mirror, ...] sorted by code point. */",
        "export const MIRRORS: readonly number[] = [" + ",".join(f"{a},{b}" for a, b in mirr) + "]",
        "",
        "/** Bidi_Paired_Bracket and type (1 open, 2 close): flat [code point, pair, type, ...]. */",
        "export const BRACKETS: readonly number[] = [" + ",".join(f"{a},{b},{t}" for a, b, t in brk) + "]",
        "",
    ]
    (ROOT / "src" / "bidi-data.ts").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(ranges)} ranges, {len(mirr)} mirror pairs, {len(brk)} brackets")


if __name__ == "__main__":
    main()
